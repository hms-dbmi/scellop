#!/usr/bin/env tsx
/**
 * Add dataset metadata to benchmark results JSON
 * This script enhances the benchmark-results.json with dataset statistics
 *
 * Usage:
 *   tsx src/benchmarks/add-metadata-to-results.ts benchmark-results.json
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

interface BenchmarkResult {
  name: string;
  [key: string]: unknown;
}

interface BenchmarkGroup {
  fullName: string;
  benchmarks: BenchmarkResult[];
}

interface BenchmarkFile {
  filepath: string;
  groups: BenchmarkGroup[];
}

interface BenchmarkResults {
  files: BenchmarkFile[];
  testResults?: {
    numTotalTestSuites: number;
    numPassedTestSuites: number;
    numFailedTestSuites: number;
    numPendingTestSuites: number;
    numTotalTests: number;
    numPassedTests: number;
    numFailedTests: number;
    numPendingTests: number;
  };
}

/**
 * Shape written by Vitest's JSON reporter, which `pnpm bench` uses since Vitest 5
 * removed `--outputJson` and the dedicated benchmark reporters.
 */
interface VitestReport {
  numTotalTestSuites: number;
  numPassedTestSuites: number;
  numFailedTestSuites: number;
  numPendingTestSuites: number;
  numTotalTests: number;
  numPassedTests: number;
  numFailedTests: number;
  numPendingTests: number;
  testResults: {
    name: string;
    assertionResults: {
      ancestorTitles: string[];
      title: string;
      benchmarks?: {
        tasks: {
          name: string;
          rank: number;
          period: number;
          latency: Record<string, number>;
          throughput: Record<string, number>;
        }[];
      }[];
    }[];
  }[];
}

/** Flattens the reporter's output into the files/groups/benchmarks shape the report generator reads. */
function normalizeResults(
  raw: VitestReport | BenchmarkResults,
): BenchmarkResults {
  if ("files" in raw) {
    return raw;
  }

  return {
    files: raw.testResults.map((file) => ({
      filepath: file.name,
      groups: file.assertionResults.flatMap((assertion) =>
        (assertion.benchmarks ?? []).map((benchmark) => ({
          fullName: [...assertion.ancestorTitles, assertion.title].join(" > "),
          benchmarks: benchmark.tasks.map((task) => ({
            name: task.name,
            rank: task.rank,
            period: task.period,
            hz: task.throughput.mean,
            mean: task.latency.mean,
            sd: task.latency.sd,
            rme: task.latency.rme,
            variance: task.latency.variance,
            min: task.latency.min,
            max: task.latency.max,
            p75: task.latency.p75,
            p99: task.latency.p99,
            p995: task.latency.p995,
            p999: task.latency.p999,
            median: task.latency.p50,
            sampleCount: task.latency.samplesCount,
          })),
        })),
      ),
    })),
    testResults: {
      numTotalTestSuites: raw.numTotalTestSuites,
      numPassedTestSuites: raw.numPassedTestSuites,
      numFailedTestSuites: raw.numFailedTestSuites,
      numPendingTestSuites: raw.numPendingTestSuites,
      numTotalTests: raw.numTotalTests,
      numPassedTests: raw.numPassedTests,
      numFailedTests: raw.numFailedTests,
      numPendingTests: raw.numPendingTests,
    },
  };
}

/** Shape of one entry in benchmark-dataset-stats.json, written by setup-benchmarks.ts */
interface DetailedDatasetStats {
  name: string;
  stats: {
    rows: number;
    cols: number;
    nonZeroCells: number;
    totalCells: number;
    density: string;
  };
  rowSums: {
    total: number;
    average: number;
    min: number;
    max: number;
    range: number;
  };
}

interface DatasetMetadata {
  name: string;
  rows: number;
  cols: number;
  nonZeroCells: number;
  totalCells: number;
  density: string;
  type: "synthetic" | "real-world";
  rowSums?: {
    total: number;
    average: number;
    min: number;
    max: number;
    range: number;
  };
  colSums?: {
    total: number;
    average: number;
    min: number;
    max: number;
    range: number;
  };
}

/**
 * Extract dataset name from benchmark name
 * Format: "name" or "name - description" or "name @2x resolution"
 */
function extractDatasetName(benchmarkName: string): string | null {
  // Match patterns like:
  // "tiny"
  // "hubmap-lung @2x resolution"
  // "medium - 10% expanded rows"
  // "large - violin aggregation"
  const match = benchmarkName.match(/^([\w-]+)(?:\s+[@-]|$)/);

  if (!match) return null;

  return match[1];
}

interface EnhancedBenchmarkResults extends BenchmarkResults {
  datasets: DatasetMetadata[];
}

/**
 * Add metadata to benchmark results
 */
function addMetadataToResults(
  results: BenchmarkResults,
): EnhancedBenchmarkResults {
  const enhancedResults = { ...results };
  const datasetMap = new Map<string, DatasetMetadata>();

  // Load detailed dataset stats from file (generated by setup-benchmarks.ts)
  let detailedStats: DetailedDatasetStats[] = [];
  try {
    const statsPath = resolve("benchmark-dataset-stats.json");
    const statsJson = readFileSync(statsPath, "utf-8");
    detailedStats = JSON.parse(statsJson);
  } catch {
    console.error("❌ Could not load benchmark-dataset-stats.json");
    console.error("Make sure benchmarks have been run to generate this file.");
    return { ...enhancedResults, datasets: [] };
  }

  // Create a map from stats for quick lookup
  const statsMap = new Map(detailedStats.map((s) => [s.name, s]));

  // First pass: collect unique datasets from benchmark names
  for (const file of enhancedResults.files) {
    for (const group of file.groups) {
      for (const bench of group.benchmarks) {
        const datasetName = extractDatasetName(bench.name);
        if (datasetName && !datasetMap.has(datasetName)) {
          // Find matching detailed stats
          const detailedStat = statsMap.get(datasetName);
          if (detailedStat) {
            const metadata: DatasetMetadata = {
              name: datasetName,
              rows: detailedStat.stats.rows,
              cols: detailedStat.stats.cols,
              nonZeroCells: detailedStat.stats.nonZeroCells,
              totalCells: detailedStat.stats.totalCells,
              density: detailedStat.stats.density,
              type: datasetName.includes("-") ? "real-world" : "synthetic",
              rowSums: {
                total: detailedStat.rowSums.total,
                average: detailedStat.rowSums.average,
                min: detailedStat.rowSums.min,
                max: detailedStat.rowSums.max,
                range: detailedStat.rowSums.range,
              },
            };
            datasetMap.set(datasetName, metadata);
          }
        }
      }
    }
  }

  // Add datasets array to results
  return {
    ...enhancedResults,
    datasets: Array.from(datasetMap.values()).sort((a, b) => {
      // Sort by type (synthetic first), then by total cells
      if (a.type !== b.type) {
        return a.type === "synthetic" ? -1 : 1;
      }
      return a.totalCells - b.totalCells;
    }),
  };
}

// Main execution
try {
  const inputPath = process.argv[2] || resolve("benchmark-results.json");
  const resultsJson = readFileSync(inputPath, "utf-8");
  const results = normalizeResults(
    JSON.parse(resultsJson) as VitestReport | BenchmarkResults,
  );

  const enhanced = addMetadataToResults(results);

  writeFileSync(inputPath, JSON.stringify(enhanced, null, 2));

  console.log(
    `✅ Added metadata for ${enhanced.datasets?.length || 0} datasets to ${inputPath}`,
  );

  if (enhanced.datasets) {
    console.log("\nDatasets included:");
    for (const dataset of enhanced.datasets) {
      console.log(
        `  ${dataset.name}: ${dataset.rows}×${dataset.cols} (${dataset.nonZeroCells} cells, ${dataset.density} density, ${dataset.type})`,
      );
      if (dataset.rowSums) {
        console.log(
          `    Row sums: total=${dataset.rowSums.total}, avg=${dataset.rowSums.average.toFixed(2)}, range=${dataset.rowSums.min}-${dataset.rowSums.max}`,
        );
      }
    }
  }
} catch (error) {
  console.error("❌ Error adding metadata:", error);
  console.log(
    "\nUsage:\n  tsx src/benchmarks/add-metadata-to-results.ts [path-to-benchmark-results.json]",
  );
  process.exit(1);
}
